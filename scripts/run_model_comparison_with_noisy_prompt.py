        print(header)
        print("-"*70)
        for level in COMPLEXITY_LEVELS:
            row = f"{level.capitalize():<14}"
            for key in self.MODEL_CONFIGS:
                val = by_cx[level].get(key, {}).get("success_rate")
                row += f"{('{:.1%}'.format(val) if val is not None else 'N/A'):>{W}}"
