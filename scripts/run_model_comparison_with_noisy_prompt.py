# ---------------------------------------------------------------------------
# Load noisy prompts from CSV
# ---------------------------------------------------------------------------

def _load_noisy_prompts(csv_path: Path = _NOISY_CSV) -> dict:
    """
    Parse the noisy-prompt CSV and return a nested dict:
        { noise_type: { complexity: { building_key: prompt_text } } }

    The CSV has these columns:
        Building_Type, Complexity_Level,
        Spelling_Noise, Grammar_Noise, Omission_Noise, ExtraWord_Noise
    """
    prompts: dict = {nt: {lvl: {} for lvl in COMPLEXITY_LEVELS}
                     for nt in NOISE_TYPES}

    if not csv_path.exists():
        raise FileNotFoundError(
            f"Noisy-prompt CSV not found: {csv_path}\n"
            "Generate it first with the noise-injection script."
        )

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            btype     = row["Building_Type"].strip()
            level     = row["Complexity_Level"].strip().lower()

            bkey = _DISPLAY_TO_KEY.get(btype)
            if bkey is None:
                print(f"  ⚠ Unknown building type in CSV: '{btype}' — skipping row")
                continue
            if level not in COMPLEXITY_LEVELS:
                print(f"  ⚠ Unknown complexity level in CSV: '{level}' — skipping row")
                continue

            for col, noise_key in _NOISE_COL_TO_KEY.items():
                text = row.get(col, "").strip().strip('"')
                if text:
                    prompts[noise_key][level][bkey] = text

    # Validate completeness
    missing = []
    for nt in NOISE_TYPES:
        for lvl in COMPLEXITY_LEVELS:
            for bkey in _BUILDINGS:
                if bkey not in prompts[nt][lvl]:
                    missing.append(f"{nt}/{lvl}/{bkey}")
    if missing:
        print(f"  ⚠ {len(missing)} noisy prompt(s) missing from CSV:")
        for m in missing[:10]:
            print(f"     {m}")
        if len(missing) > 10:
            print(f"     … and {len(missing)-10} more")

    return prompts


