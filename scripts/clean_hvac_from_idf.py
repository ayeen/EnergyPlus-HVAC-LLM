def _is_valid_ep_type(type_name: str) -> bool:
    """
    Return True if *type_name* looks like a real EnergyPlus object-type
    name (and is therefore a genuine object-boundary marker), False if it
    is an EMS program keyword or variable name, or a known field value.

    Valid EnergyPlus types are either:
      * Namespaced  -- contain ':' (e.g. 'WaterHeater:Mixed', 'AirLoopHVAC:')
      * PascalCase  -- start with uppercase, contain at least one lowercase
                       letter, and have no underscores
                       (e.g. 'Zone', 'Building', 'Timestep', 'NodeList')

    EMS keywords (IF, ENDIF, ELSE, ELSEIF, SET, RETURN, ...) are ALL-CAPS:
    they fail the "has lowercase" test.
    EMS variable names (init_timesteps_after_doorshut, ...) are
    lowercase-with-underscores: they fail the "no underscore" test.
    Known field values (Autosize, Yes, No, ...) are excluded explicitly.
    """
    if not type_name:
        return False
    # Use only the first word (handles "SET x = 0" -> "SET"; "Zone" -> "Zone")
    word = (type_name.split()[0] if ' ' in type_name else type_name).rstrip(',;')
    if ':' in word:
        return True   # namespaced type always valid
    if '_' in word:
        return False  # EMS variable / program name
    if not word or not word[0].isupper():
        return False  # lowercase start
    if not any(c.islower() for c in word):
        return False  # ALL_CAPS -> EMS keyword (IF, ENDIF, SET, ...)
    if word in _EP_FIELD_VALUE_KEYWORDS:
        return False  # known PascalCase field value, not an object type
    return True       # PascalCase -> valid EnergyPlus type


def parse_objects(content: str):
    """
    Split IDF content into a list of (obj_type, raw_text) tuples.

    Uses potential split positions from TWO patterns, then filters out
    false-positive boundaries that are EMS body lines (keywords or names):

      * 0-indent colon pattern  -> always a valid boundary (Addendum AM style)
      * 2-space-indented line   -> valid only if the first field looks like a
                                   genuine EnergyPlus object type (see
                                   _is_valid_ep_type above)

    This correctly handles:
      * EMS:Program body lines "  init_timesteps_after_doorshut, ! Name"
        -> lowercase -> NOT a split point
      * EMS keywords "  ENDIF;" "  ELSE," "  SET x = 0,"
        -> ALL-CAPS / has space -> NOT a split point
      * Objects without a trailing ';' (implicit termination in some ASHRAE
        prototype IDFs) -> the next valid 2-space line correctly closes them
    """
    # Broad candidate-finding regex (false positives filtered below)
    candidate_re = re.compile(
        r'(?=\n  [A-Za-z][^\n]*[,;])'                 # 2-space candidates
        r'|(?=\n[A-Za-z][A-Za-z0-9_]*:[A-Za-z0-9])',  # 0-indent colon
        re.MULTILINE
    )

    valid_positions = []
    for m in candidate_re.finditer(content):
        pos = m.start()

        # Determine indentation style
        is_0indent = not content[pos + 1: pos + 3].startswith('  ')

        if is_0indent:
            # 0-indent colon pattern -> always a valid new object
            valid_positions.append(pos)
        else:
            # 2-space -> validate the type name
            line_start = pos + 1
            line_end = content.find('\n', line_start)
            if line_end < 0:
                line_end = len(content)
            line_text = content[line_start:line_end]
            raw_type = line_text.split('!')[0].strip().rstrip(',;').strip()
            if _is_valid_ep_type(raw_type):
                valid_positions.append(pos)

    if not valid_positions:
        return [('_BLANK', content)]

    # Build segments between valid object-start positions
    objects = []

    # Content before the first valid position
    prefix = content[: valid_positions[0]]
    if prefix.strip():
        objects.append(('_COMMENT', prefix))
    elif prefix:
        objects.append(('_BLANK', prefix))

    endpoints = valid_positions + [len(content)]
    for i in range(len(valid_positions)):
        seg = content[valid_positions[i]: endpoints[i + 1]]

        if not seg.strip():
            objects.append(('_BLANK', seg))
            continue

        obj_type = None
        for line in seg.splitlines():
            stripped = line.strip()
            if stripped and not stripped.startswith('!'):
                stripped = stripped.split('!')[0].strip()
                obj_type = stripped.rstrip(',;').strip()
                break

        if obj_type is None:
            objects.append(('_COMMENT', seg))
        else:
            objects.append((obj_type, seg))

    return objects


def get_object_name(raw_text: str) -> str:
    """
    Extract the Name field (second data line) from an IDF object block.
    Returns empty string if not found.
    """
    lines = raw_text.splitlines()
    data_lines = []
    for ln in lines:
        s = ln.strip()
        if s and not s.startswith('!'):
            # Strip inline comments
            s = s.split('!')[0].strip().rstrip(',;').strip()
            data_lines.append(s)

    # data_lines[0] = object type, data_lines[1] = Name (for named objects)
    if len(data_lines) >= 2:
        return data_lines[1]
    return ''


def should_keep(obj_type: str, raw_text: str) -> bool:
    """Decide whether to keep this object in the cleaned IDF."""

    # ── Always-remove list ───────────────────────────────────
    if obj_type in REMOVE_TYPES:
        return False

    # ── Name-based filter FIRST (before prefix matching) ────
    # Ensures SWH-named objects (e.g. SetpointManager:Scheduled,
    # WaterHeater:Mixed, Branch) are kept even when their type prefix
    # would otherwise be caught by the remove-prefix loop below.
    if obj_type in NAME_BASED_TYPES:
        name = get_object_name(raw_text)
        return is_swh(name)

    # ── Catch remaining sub-types via prefix matching ────────
    for remove_prefix in (
        'AirLoopHVAC:', 'AirTerminal:', 'AvailabilityManager:',
        'Chiller:', 'CoilSystem:', 'Coil:', 'Controller:', 'Curve:',
        'EnergyManagementSystem:', 'Fan:', 'HeatExchanger:Air',
        'HeatExchanger:', 'Humidifier:',
        'Refrigeration:',
        # ALL SetpointManager sub-types are removed; the only exception
        # (SetpointManager:Scheduled for SWH) is handled by NAME_BASED_TYPES above
        'SetpointManager:',
        'ZoneHVAC:',
        # Condenser-side objects: CondenserLoop/EquipmentList/OperationSchemes
        # are all condenser-loop exclusive; prefix 'Condenser' catches them all
        'Condenser',
        # Headered pump types (central plant; SWH always uses Pump:ConstantSpeed)
        'HeaderedPumps:',
    ):
        if obj_type.startswith(remove_prefix):
            return False

    # ── Everything else is kept (building envelope, loads…) ──
    return True


def clean_idf(input_path: str, output_path: str):
    with open(input_path, encoding='utf-8', errors='replace') as f:
        content = f.read()

    objects = parse_objects(content)

    kept, removed = [], []
    for obj_type, raw in objects:
        if obj_type in ('_BLANK', '_COMMENT'):
            kept.append(raw)
            continue
        if should_keep(obj_type, raw):
            kept.append(raw)
        else:
            removed.append(obj_type)

    # ── Stats ────────────────────────────────────────────────
    from collections import Counter
    removed_counts = Counter(removed)
    print(f"\n{'='*60}")
    print(f"HVAC Cleaning Report: {Path(input_path).name}")
    print(f"{'='*60}")
    print(f"  Objects kept   : {sum(1 for o,_ in objects if o not in ('_BLANK','_COMMENT')) - len(removed)}")
    print(f"  Objects removed: {len(removed)}")
    print(f"\n  Removed by type:")
    for t, c in sorted(removed_counts.items(), key=lambda x: -x[1]):
        print(f"    {c:4d}  {t}")
    print()

    # ── Write cleaned IDF ────────────────────────────────────
    cleaned = ''.join(kept)

    # Remove excessive blank lines (more than 2 consecutive)
    cleaned = re.sub(r'\n{4,}', '\n\n\n', cleaned)

    # ── EnergyPlus v22→v25.2 compatibility fixes ─────────────
    # People: "ZoneAveraged" renamed to "EnclosureAveraged" in v25.2 IDD
    n_mrt = cleaned.count('ZoneAveraged')
    if n_mrt:
        cleaned = cleaned.replace('ZoneAveraged', 'EnclosureAveraged')
        print(f"  ⚠️  People MRT: {n_mrt} 'ZoneAveraged' → 'EnclosureAveraged' (v25.2 fix)")

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(cleaned)

    print(f"  ✅ Written to: {output_path}")
    print(f"  Original: {Path(input_path).stat().st_size // 1024} KB  →  "
          f"Cleaned: {Path(output_path).stat().st_size // 1024} KB")


if __name__ == '__main__':
    if len(sys.argv) < 3:
        print("Usage: python clean_hvac_from_idf.py <input.idf> <output.idf>")
        sys.exit(1)
    clean_idf(sys.argv[1], sys.argv[2])
