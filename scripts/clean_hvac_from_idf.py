# SWH keyword — any object whose name contains this is kept
SWH_KEYWORDS = ('SWHSYS', 'SWH ')


def is_swh(name: str) -> bool:
    """Return True if the object name belongs to the SWH plant loop."""
    upper = name.upper()
    return any(kw in upper for kw in SWH_KEYWORDS)


# Known EnergyPlus field *values* that happen to be PascalCase and may appear
